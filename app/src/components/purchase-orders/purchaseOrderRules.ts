import type { PurchaseOrderDetail, PurchaseOrderStatus } from "@/types/purchaseOrder";

const LINES_EDITABLE: ReadonlySet<PurchaseOrderStatus> = new Set(["draft", "open"]);
const CANCELLABLE: ReadonlySet<PurchaseOrderStatus> = new Set(["draft", "open", "ready_for_delivery"]);
const RECEIVABLE: ReadonlySet<PurchaseOrderStatus> = new Set(["open", "ready_for_delivery"]);

export const PURCHASE_ORDER_STATUSES: readonly PurchaseOrderStatus[] = [
  "draft",
  "open",
  "ready_for_delivery",
  "closed",
  "cancelled",
];

export function canEditPurchaseOrder(status: PurchaseOrderStatus): boolean {
  return LINES_EDITABLE.has(status);
}

export function supplierNameOf(purchaseOrder: Pick<PurchaseOrderDetail, "supplier">): string {
  return purchaseOrder.supplier?.name ?? "No supplier yet";
}

export function isAutoGenerated(purchaseOrder: Pick<PurchaseOrderDetail, "source">): boolean {
  return purchaseOrder.source !== "manual";
}

export function finalizeBlocker(purchaseOrder: PurchaseOrderDetail): string | null {
  if (!purchaseOrder.supplier) {
    return "Choose a supplier before finalizing.";
  }
  if (purchaseOrder.items.some((line) => line.unit_cost <= 0)) {
    return "Enter a unit cost for every item before finalizing.";
  }
  return null;
}

export function canMarkPurchaseOrderReady(status: PurchaseOrderStatus): boolean {
  return status === "open";
}

export function canCancelPurchaseOrder(status: PurchaseOrderStatus): boolean {
  return CANCELLABLE.has(status);
}

export function canReceivePurchaseOrder(status: PurchaseOrderStatus): boolean {
  return RECEIVABLE.has(status);
}

export function lineTotal(quantity: number, unitCost: number, discount: number): number {
  return quantity * unitCost - discount;
}
